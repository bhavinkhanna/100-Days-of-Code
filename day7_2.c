// Write a program to input a character and check whether it
//  is a vowel or consonant using if–else.
#include <stdio.h>
int main(){
    char c,a,e,i,o,u;
    printf("Enter a character:\n");
    scanf("%c",&c);
    if(c=='a')
        printf("Entered character is a vowel");
    else if (c=='e')
        printf("Entered character is a vowel");
    else if (c=='i')
        printf("Entered character is a vowel");
    else if (c=='o')
        printf("Entered character is a vowel");
    else if (c=='u')
        printf("Entered character is a vowel");
    else
        printf("Entered character is a consonant");
    
    return 0;
}